// Converts the CC0 Quaternius "Ultimate Guns Pack" OBJ models into js/weapon-meshes.js.
// Run once after changing the source models:  node tools/obj2js.js
// Keeps the game build-free and file://-friendly (no runtime fetch of model files).
const fs = require('fs');
const path = require('path');

globalThis.window = globalThis;
require('../js/config.js');
require('../js/models.js');
const BS = globalThis.BloxStrike;

const SRC = path.join(__dirname, '..', 'assets', 'models', 'quaternius-ultimate-guns');
const OUT = path.join(__dirname, '..', 'js', 'weapon-meshes.js');
const GUNS = { ar: 'AssaultRifle2_1', shotgun: 'Shotgun_1', smg: 'SubmachineGun_3', sniper: 'SniperRifle_2' };
const NOT_BODY = new Set(['Black', 'Glass']); // never tinted by weapon color / skins

function parseMtl(file) {
  const colors = {};
  let cur = null;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const p = line.trim().split(/\s+/);
    if (p[0] === 'newmtl') cur = p[1];
    else if (p[0] === 'Kd' && cur) colors[cur] = p.slice(1, 4).map((x) => +Math.pow(Number(x), 1 / 2.2).toFixed(3)); // linear -> sRGB
  }
  return colors;
}

function parseObj(file) {
  const verts = [];
  const groups = {}; // material -> flat triangle vertex indices
  let mtl = 'default';
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const p = line.trim().split(/\s+/);
    if (p[0] === 'v') verts.push(p.slice(1, 4).map(Number));
    else if (p[0] === 'usemtl') mtl = p[1];
    else if (p[0] === 'f') {
      const idx = p.slice(1).map((s) => {
        const i = parseInt(s.split('/')[0], 10);
        return i < 0 ? verts.length + i : i - 1;
      });
      const g = (groups[mtl] = groups[mtl] || []);
      for (let k = 1; k + 1 < idx.length; k++) g.push(idx[0], idx[k], idx[k + 1]); // fan triangulation
    }
  }
  return { verts, groups };
}

const out = {};
for (const [id, name] of Object.entries(GUNS)) {
  const old = BS.MODELS.weapons[id];
  const { verts, groups } = parseObj(path.join(SRC, name + '.obj'));
  const colors = parseMtl(path.join(SRC, name + '.mtl'));

  // Barrel runs along +X in the source; the game's forward is -Z: (x, y, z) -> (z, y, -x).
  const rot = verts.map(([x, y, z]) => [z, y, -x]);
  let minZ = Infinity, maxZ = -Infinity, minX = Infinity, maxX = -Infinity;
  for (const v of rot) {
    minZ = Math.min(minZ, v[2]); maxZ = Math.max(maxZ, v[2]);
    minX = Math.min(minX, v[0]); maxX = Math.max(maxX, v[0]);
  }
  // Fit length to the old box model (muzzle tip .. rear of stock) and put the barrel tip on the old muzzle point.
  let oldMaxZ = -Infinity;
  for (const pt of old.parts) oldMaxZ = Math.max(oldMaxZ, pt.p[2] + pt.s[2] / 2);
  const scale = (oldMaxZ - old.muzzle[2]) / (maxZ - minZ);
  const tip = rot.filter((v) => v[2] < minZ + (maxZ - minZ) * 0.03);
  const barrelY = tip.reduce((s, v) => s + v[1], 0) / tip.length;
  const t = [-(minX + maxX) / 2 * scale + old.muzzle[0], old.muzzle[1] - barrelY * scale, old.muzzle[2] - minZ * scale];

  const pos = [];
  for (const v of rot) for (let k = 0; k < 3; k++) pos.push(Math.round((v[k] * scale + t[k]) * 1000));

  // The biggest non-black material carries the weapon color / CS2-style skin.
  let body = null;
  for (const m of Object.keys(groups)) if (!NOT_BODY.has(m) && (!body || groups[m].length > groups[body].length)) body = m;

  out[id] = {
    source: name,
    groups: Object.keys(groups).map((m) => ({ mtl: m, color: colors[m] || [0.5, 0.5, 0.5], body: m === body, idx: groups[m] })),
    pos,
  };
  const tris = Object.values(groups).reduce((s, g) => s + g.length / 3, 0);
  console.log(`${id}: ${name} ${verts.length} verts, ${tris} tris, body=${body}, scale=${scale.toFixed(4)}`);
}

const header =
  '// GENERATED by tools/obj2js.js — do not edit by hand.\n' +
  '// Weapon meshes from the "Ultimate Guns Pack" by Quaternius, CC0 1.0 (assets/models/quaternius-ultimate-guns/License.txt).\n' +
  '// Positions are integers in 1/1000 units; groups index into them as triangles.\n';
fs.writeFileSync(
  OUT,
  header +
    '(function (global) {\n  const BS = (global.BloxStrike = global.BloxStrike || {});\n  BS.WEAPON_MESHES = ' +
    JSON.stringify(out) +
    ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n'
);
console.log('wrote', OUT, (fs.statSync(OUT).size / 1024).toFixed(0) + ' KB');
